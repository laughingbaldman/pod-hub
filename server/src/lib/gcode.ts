/**
 * Read slicer metadata out of a G-code file without loading it all.
 * OrcaSlicer writes a short header near the top and, at the end, a summary
 * ("; estimated printing time (normal mode) = ...", "; filament used [g] = ...") followed
 * by a CONFIG_BLOCK of "; key = value" lines (printer_model, nozzle_diameter, printable_area ...).
 * Bambu Studio, PrusaSlicer and Cura variants are handled best-effort.
 */
import fs from "node:fs";

export interface GcodeMeta {
  slicer: string | null;
  slicerVersion: string | null;
  printerModel: string | null;
  printerSettingsId: string | null;
  nozzleMm: number | null;
  material: string | null;
  filamentSettingsId: string | null;
  layerHeight: number | null;
  layers: number | null;
  estSeconds: number | null;
  filamentG: number | null;
  filamentMm: number | null;
  bedX: number | null;
  bedY: number | null;
  maxZ: number | null;
  printableHeight: number | null;
  config: Record<string, string>;
}

const HEAD_BYTES = 256 * 1024;
const TAIL_BYTES = 2 * 1024 * 1024;

/** "1d 2h 3m 4s" / "23m 46s" / "3600" -> seconds */
export function parseDuration(text: string): number | null {
  const t = text.trim();
  if (/^\d+(\.\d+)?$/.test(t)) return Math.round(Number(t));
  let total = 0;
  let matched = false;
  for (const m of t.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/gi)) {
    matched = true;
    const n = Number(m[1]);
    total += n * ({ d: 86400, h: 3600, m: 60, s: 1 } as Record<string, number>)[m[2].toLowerCase()];
  }
  return matched ? Math.round(total) : null;
}

/** First number of a possibly comma-separated multi-extruder list, or the sum when asked. */
function firstNum(value: string | undefined): number | null {
  if (value === undefined) return null;
  const n = Number(value.split(/[,;]/)[0].trim());
  return Number.isFinite(n) ? n : null;
}
function sumNums(value: string | undefined): number | null {
  if (value === undefined) return null;
  const nums = value.split(/[,;]/).map((v) => Number(v.trim())).filter((n) => Number.isFinite(n));
  return nums.length ? Math.round(nums.reduce((a, b) => a + b, 0) * 100) / 100 : null;
}
function firstStr(value: string | undefined): string | null {
  if (!value) return null;
  const v = value.split(";")[0].trim().replace(/^"|"$/g, "");
  return v || null;
}

/** "0x0,256x0,256x256,0x256" -> {x:256,y:256} */
export function parseArea(value: string | undefined): { x: number; y: number } | null {
  if (!value) return null;
  const pts = value
    .split(",")
    .map((p) => p.trim().split("x").map(Number))
    .filter((p) => p.length === 2 && p.every(Number.isFinite));
  if (pts.length < 3) return null;
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return { x: Math.max(...xs) - Math.min(...xs), y: Math.max(...ys) - Math.min(...ys) };
}

export function parseGcodeText(head: string, tail: string): GcodeMeta {
  const config: Record<string, string> = {};
  const loose: Record<string, string> = {};
  const lines = (head + "\n" + tail).split(/\r?\n/);
  let slicer: string | null = null;
  let slicerVersion: string | null = null;

  for (const raw of lines) {
    const line = raw.trim();
    if (!line.startsWith(";")) continue;
    const body = line.replace(/^;+\s*/, "");

    const gen = body.match(/^generated by\s+([A-Za-z][\w .-]*?)\s+v?(\d+(?:\.\d+)+[\w.+-]*)/i);
    if (gen && !slicer) {
      slicer = gen[1].trim();
      slicerVersion = gen[2];
      continue;
    }
    const bambu = body.match(/^(BambuStudio|OrcaSlicer)\s+v?(\d+(?:\.\d+)+[\w.+-]*)$/i);
    if (bambu && !slicer) {
      slicer = bambu[1];
      slicerVersion = bambu[2];
      continue;
    }
    const cura = body.match(/^Generated with Cura_SteamEngine\s+(\S+)/i);
    if (cura && !slicer) {
      slicer = "Cura";
      slicerVersion = cura[1];
      continue;
    }
    // Header pairs can share a line: "model printing time: 40m 45s; total estimated time: 48m 41s"
    for (const piece of body.split(/;\s+(?=[a-z])/i)) {
      const eq = piece.match(/^([A-Za-z_][\w \[\]^\/().-]*?)\s*=\s*(.*)$/);
      if (eq) {
        const key = eq[1].trim();
        if (/^[a-z0-9_]+$/.test(key)) config[key] = eq[2].trim();
        else loose[key.toLowerCase()] = eq[2].trim();
        continue;
      }
      const colon = piece.match(/^([A-Za-z_][\w \[\]^\/().-]*?)\s*:\s*(.*)$/);
      if (colon) loose[colon[1].trim().toLowerCase()] = colon[2].trim();
    }
  }

  const estText =
    loose["estimated printing time (normal mode)"] ??
    loose["total estimated time"] ??
    loose["estimated printing time"] ??
    loose["time"];
  const area = parseArea(config.printable_area ?? config.bed_shape);
  const filamentMmRaw = loose["filament used [mm]"] ?? loose["total filament length [mm]"];
  let filamentMm = sumNums(filamentMmRaw);
  if (filamentMm === null && loose["filament used"]) {
    const m = loose["filament used"].match(/([\d.]+)\s*m\b/);
    if (m) filamentMm = Math.round(Number(m[1]) * 1000 * 100) / 100;
  }
  const layersText = loose["total layer number"] ?? loose["total layers count"] ?? loose["layer_count"] ?? config.total_layer_count;
  const nozzle = firstNum(config.nozzle_diameter);
  const height = firstNum(config.printable_height ?? config.max_print_height);

  return {
    slicer,
    slicerVersion,
    printerModel: firstStr(config.printer_model) ?? firstStr(config.printer_notes?.match(/PRINTER_MODEL_(\S+)/)?.[1]),
    printerSettingsId: firstStr(config.printer_settings_id),
    nozzleMm: nozzle,
    material: firstStr(config.filament_type),
    filamentSettingsId: firstStr(config.filament_settings_id),
    layerHeight: firstNum(config.layer_height),
    layers: layersText ? Math.round(Number(layersText.split(/[ ,]/)[0])) || null : null,
    estSeconds: estText ? parseDuration(estText) : null,
    filamentG: sumNums(loose["total filament used [g]"] ?? loose["filament used [g]"] ?? loose["total filament weight [g]"]),
    filamentMm,
    bedX: area?.x ?? null,
    bedY: area?.y ?? null,
    maxZ: firstNum(loose["max_z_height"]),
    printableHeight: height,
    config,
  };
}

function readSlice(fd: number, start: number, length: number): string {
  const buf = Buffer.alloc(length);
  const n = fs.readSync(fd, buf, 0, length, start);
  return buf.subarray(0, n).toString("utf8");
}

export function parseGcodeFile(file: string): GcodeMeta {
  const size = fs.statSync(file).size;
  const fd = fs.openSync(file, "r");
  try {
    const head = readSlice(fd, 0, Math.min(HEAD_BYTES, size));
    const tailStart = Math.max(HEAD_BYTES, size - TAIL_BYTES);
    const tail = tailStart < size ? readSlice(fd, tailStart, size - tailStart) : "";
    return parseGcodeText(head, tail);
  } finally {
    fs.closeSync(fd);
  }
}
